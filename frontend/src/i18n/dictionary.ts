export type Dict = (typeof dict)["es"];

/**
 * Compile-time parity check between the two trees.
 *
 * Every lookup in the app is `t.section.key`, typed against the Spanish tree.
 * Without this, adding a Spanish string and forgetting the English one would
 * type-check fine and then render `undefined` in an English demo. This makes
 * that a build error instead.
 */
type Mirror<T> = { [K in keyof T]: T[K] extends object ? Mirror<T[K]> : string };
const _englishCoversSpanish: Mirror<typeof dict.es> = dict.en;
const _spanishCoversEnglish: Mirror<typeof dict.en> = dict.es;
void _englishCoversSpanish;
void _spanishCoversEnglish;

/** Pick the right side of a bilingual API field. */
export function pickLang<T>(lang: Lang, es: T, en: T): T {
  return lang === "es" ? es : en;
}
